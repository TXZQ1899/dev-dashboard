#!/usr/bin/env bash
# Check whether a Linux directory may be used by processes, service configs, containers or jobs.
# Read-only. No files are modified.
set -uo pipefail
export LC_ALL=C

usage() { echo "Usage: $0 DIRECTORY [--deep]"; echo "  --deep  Search additional deployment locations (potentially slow)."; }
if [[ $# -lt 1 || $# -gt 2 || "${1:-}" == '-h' || "${1:-}" == '--help' ]]; then usage; [[ "${1:-}" == '-h' || "${1:-}" == '--help' ]] && exit 0 || exit 2; fi
INPUT=$1
DEEP=0
if [[ $# -eq 2 ]]; then [[ "$2" == '--deep' ]] || { usage; exit 2; }; DEEP=1; fi
[[ -d "$INPUT" ]] || { echo "ERROR: Directory does not exist: $INPUT" >&2; exit 2; }
DIR=$(realpath -e -- "$INPUT") || exit 2
[[ "$DIR" != / ]] || { echo 'ERROR: Refusing to scan filesystem root.' >&2; exit 2; }
if [[ $EUID -ne 0 ]]; then echo 'INFO: Running unprivileged; some process/config/socket details may be hidden.'; fi
MATCHES=0; WARNINGS=0; ACTIVE=0; REFERENCES=0
RELATED_PIDS=()
add_pid() { [[ "$1" =~ ^[0-9]+$ ]] && RELATED_PIDS+=("$1"); }
section() { printf '\n========== %s ==========\n' "$1"; }
found() { MATCHES=$((MATCHES+1)); REFERENCES=$((REFERENCES+1)); }
active_found() { MATCHES=$((MATCHES+1)); ACTIVE=$((ACTIVE+1)); }
warn() { WARNINGS=$((WARNINGS+1)); printf 'NOTE: %s\n' "$*"; }

section 'Target'
printf 'Input: %s\nResolved path: %s\n' "$INPUT" "$DIR"
ls -ld -- "$INPUT" "$DIR" 2>/dev/null || :

section '1. Open files and working directories (lsof)'
if command -v lsof >/dev/null 2>&1; then
  LSOF_OUT=$(mktemp) || exit 2
  LSOF_ERR=$(mktemp) || { rm -f "$LSOF_OUT"; exit 2; }
  lsof -nP +D "$DIR" >"$LSOF_OUT" 2>"$LSOF_ERR"
  lsof_rc=$?
  if [[ -s "$LSOF_OUT" ]]; then
    cat "$LSOF_OUT"
    while IFS= read -r candidate; do add_pid "$candidate"; done < <(awk 'NR>1 && $2 ~ /^[0-9]+$/ {print $2}' "$LSOF_OUT" | sort -u)
    active_found
  else
    echo 'No open files reported at this instant.'
  fi
  # lsof commonly returns 1 when no matching files are found. This is not itself a failure.
  # Stderr, unexpected exit codes, or partial records indicate an incomplete scan.
  if [[ -s "$LSOF_ERR" ]]; then
    warn "lsof emitted diagnostic messages (exit=$lsof_rc); scan may be incomplete:"
    cat "$LSOF_ERR"
  elif (( lsof_rc != 0 && lsof_rc != 1 )); then
    warn "lsof exited unexpectedly with status $lsof_rc."
  elif (( lsof_rc == 1 )) && [[ -s "$LSOF_OUT" ]]; then
    warn 'lsof returned partial records with nonzero status; verify completeness.'
  fi
  rm -f "$LSOF_OUT" "$LSOF_ERR"
else
  echo 'INFO: lsof not installed; using /proc file descriptors and cwd fallback below.'
fi

section '2. Process cwd, cmdline, and open file descriptors (/proc fallback)'
PROC_COUNT=0; FD_COUNT=0; PROC_INACCESSIBLE=0; PROC_SCANNED=0
# PIDs generated by our own subprocesses must not be interpreted as business usage.
SELF_PID=$$
for p in /proc/[0-9]*; do
  [[ -d "$p" ]] || continue
  pid=${p##*/}
  [[ "$pid" == "$SELF_PID" || "$pid" == "$PPID" ]] && continue
  if [[ ! -r "$p/cmdline" ]]; then
    [[ -d "$p" ]] && PROC_INACCESSIBLE=$((PROC_INACCESSIBLE+1))
    continue
  fi
  PROC_SCANNED=$((PROC_SCANNED+1))
  cwd=$(readlink -f -- "$p/cwd" 2>/dev/null) || cwd=''
  cmd=$(tr '\0' ' ' < "$p/cmdline" 2>/dev/null) || cmd=''
  # Avoid scanning helper processes containing our target directory in their args.
  hit=''
  if [[ "$cwd" == "$DIR" || "$cwd" == "$DIR/"* ]]; then hit='cwd'; fi
  if [[ "$cmd" != *"check_usage.sh"* && "$cmd" != *"lsof "* && ( "$cmd" == *"$DIR"* || ( "$INPUT" != "$DIR" && "$cmd" == *"$INPUT"* ) ) ]]; then
    hit="${hit:+$hit,}cmdline"
  fi
  if [[ -n "$hit" ]]; then
    printf 'PID=%s match=%s cwd=%q cmd=%s\n' "$pid" "$hit" "$cwd" "${cmd:0:350}"
    add_pid "$pid"
    PROC_COUNT=$((PROC_COUNT+1))
  fi
  # fd links can be unreadable for another user's process; these are silent
  # here, with a coverage warning below when running unprivileged.
  if [[ -r "$p/fd" && -x "$p/fd" ]]; then
    for fd in "$p"/fd/*; do
      [[ -L "$fd" ]] || continue
      dest=$(readlink -- "$fd" 2>/dev/null) || continue
      dest=${dest% (deleted)}
      if [[ "$dest" == "$DIR" || "$dest" == "$DIR/"* ]]; then
        printf 'PID=%s match=fd FD=%s file=%s\n' "$pid" "${fd##*/}" "$dest"
        add_pid "$pid"
        FD_COUNT=$((FD_COUNT+1))
      fi
    done
  fi
done
if (( PROC_COUNT > 0 || FD_COUNT > 0 )); then
  active_found
else
  echo 'No directory-related cwd/cmdline/open-fd references found in accessible /proc entries.'
fi
if (( EUID != 0 )); then
  warn 'Unprivileged /proc scan: other users cwd/fd and cmdline may be inaccessible; negative results are incomplete.'
elif (( PROC_INACCESSIBLE > 0 )); then
  warn "$PROC_INACCESSIBLE process cmdline entries were inaccessible or disappeared during scan."
fi
printf 'Accessible processes inspected: %d; open-fd matches: %d\n' "$PROC_SCANNED" "$FD_COUNT"
echo 'LIMITATION: Dynamically accessed files may be closed before scanning; relative paths may not occur in cmdline.'

section '3. Service configuration references'
CONFIG_DIRS=(/etc/nginx /etc/apache2 /etc/httpd /etc/systemd/system /usr/lib/systemd/system /lib/systemd/system /etc/supervisor /etc/supervisord.d /etc/cron.d /etc/cron.daily /etc/cron.hourly /etc/cron.weekly /etc/cron.monthly /etc/crontab)
if (( DEEP )); then CONFIG_DIRS+=(/etc/opt /opt /srv /var/spool/cron /var/spool/cron/crontabs); fi
EXISTING=()
for d in "${CONFIG_DIRS[@]}"; do [[ -e "$d" ]] && EXISTING+=("$d"); done
if ((${#EXISTING[@]})); then
  TMP=$(mktemp)
  # Use fixed-string exact path search, avoiding logs and large binary files.
  grep -RInF -m 4 --binary-files=without-match --exclude='*.log' --exclude='*.gz' --exclude='*.jar' --exclude='*.war' --exclude='*.tar' --exclude='*.zip' --exclude='*.map' -- "$DIR" "${EXISTING[@]}" > "$TMP" 2>/dev/null || :
  if [[ "$INPUT" != "$DIR" ]]; then grep -RInF -m 4 --binary-files=without-match --exclude='*.log' --exclude='*.gz' --exclude='*.jar' --exclude='*.war' --exclude='*.tar' --exclude='*.zip' --exclude='*.map' -- "$INPUT" "${EXISTING[@]}" >> "$TMP" 2>/dev/null || :; fi
  if [[ -s "$TMP" ]]; then sort -u "$TMP"; found; else echo 'No direct absolute-path references found in scanned configs.'; fi
  rm -f "$TMP"
fi
if command -v nginx >/dev/null 2>&1; then
  TMP=$(mktemp)
  nginx -T > "$TMP" 2>/dev/null || warn 'nginx -T returned a non-zero status (check nginx configuration).'
  if grep -nF -- "$DIR" "$TMP" || { [[ "$INPUT" != "$DIR" ]] && grep -nF -- "$INPUT" "$TMP"; }; then found; fi
  rm -f "$TMP"
fi

section '4. Listening TCP ports of directory-related processes'
if ! command -v ss >/dev/null 2>&1; then
  warn 'ss is not installed.'
elif (( ${#RELATED_PIDS[@]} == 0 )); then
  echo 'No directory-related PID found; cannot attribute any listening port.'
else
  PID_LIST=$(printf '%s\n' "${RELATED_PIDS[@]}" | sort -un | paste -sd, -)
  SS_OUT=$(mktemp) || exit 2
  SS_ERR=$(mktemp) || { rm -f "$SS_OUT"; exit 2; }
  if ss -H -lntp >"$SS_OUT" 2>"$SS_ERR"; then
    PORT_ROWS=$(mktemp) || exit 2
    awk -v target=",${PID_LIST}," '
      {
        addr=$4
        port=addr
        sub(/^.*:/, "", port)
        while (match($0, /pid=[0-9]+/)) {
          pid=substr($0,RSTART+4,RLENGTH-4)
          if (index(target, "," pid ",") > 0) print pid "\t" addr "\t" port
          $0=substr($0,RSTART+RLENGTH)
        }
      }
    ' "$SS_OUT" | sort -u >"$PORT_ROWS"
    if [[ -s "$PORT_ROWS" ]]; then
      printf '%-9s %-20s %-32s %s\n' 'PID' 'PROCESS' 'LOCAL_ADDRESS:PORT' 'PORT'
      while IFS=$'\t' read -r listener_pid local_address port; do
        proc_name=$(cat "/proc/$listener_pid/comm" 2>/dev/null) || proc_name='(exited)'
        printf '%-9s %-20s %-32s %s\n' "$listener_pid" "$proc_name" "$local_address" "$port"
      done <"$PORT_ROWS"
      printf 'Related listening sockets: %s\n' "$(wc -l < "$PORT_ROWS" | tr -d ' ')"
    else
      echo 'No listening TCP port attributable to directory-related PIDs.'
      if (( EUID != 0 )); then warn 'Socket PID ownership may be hidden from unprivileged ss; no matching port does not establish no listener.'; fi
    fi
    rm -f "$PORT_ROWS"
  else
    warn 'ss could not enumerate TCP listening sockets.'
    [[ ! -s "$SS_ERR" ]] || cat "$SS_ERR" >&2
  fi
  rm -f "$SS_OUT" "$SS_ERR"
fi

section '5. Symlinks resolving to directory'
PARENT=$(dirname -- "$DIR")
TMP=$(mktemp)
find "$PARENT" -maxdepth 2 -type l -print 2>/dev/null | while IFS= read -r link; do
  dest=$(realpath -e -- "$link" 2>/dev/null) || continue
  if [[ "$dest" == "$DIR" || "$dest" == "$DIR/"* ]]; then printf '%s -> %s\n' "$link" "$dest"; fi
done > "$TMP"
if [[ -s "$TMP" ]]; then cat "$TMP"; found; else echo 'No matching symlinks at parent depth <= 2.'; fi
rm -f "$TMP"

section '6. Docker bind mounts (including stopped containers)'
if command -v docker >/dev/null; then
  IDS=$(docker ps -aq 2>/dev/null) || { warn 'Could not list Docker containers (permissions or daemon).'; IDS=''; }
  if [[ -n "$IDS" ]]; then
    TMP=$(mktemp)
    while IFS= read -r id; do
      docker inspect --format '{{.Name}} status={{.State.Status}}{{range .Mounts}}{{printf "\n  %s -> %s" .Source .Destination}}{{end}}' "$id" 2>/dev/null | awk -v dir="$DIR" '
      /^\// { header=$0; next }
      /^  / { src=$0; sub(/ -> .*/, "", src); sub(/^  /, "", src); if(src == dir || index(src, dir "/") == 1 || index(dir, src "/") == 1) print header "\n" $0 }
      ' >> "$TMP"
    done <<< "$IDS"
    if [[ -s "$TMP" ]]; then cat "$TMP"; found; else echo 'No matching Docker bind mounts found among inspectable containers.'; fi
    rm -f "$TMP"
  else echo 'No containers detected or Docker unavailable.'; fi
else echo 'Docker command not installed.'; fi

section '7. Cron entries (user crontabs)'
if command -v crontab >/dev/null && [[ $EUID -eq 0 ]]; then
  TMP=$(mktemp)
  while IFS=: read -r user _; do
    crontab -u "$user" -l 2>/dev/null | grep -nF -- "$DIR" | sed "s/^/user=$user line=/" >> "$TMP" || :
  done < /etc/passwd
  if [[ -s "$TMP" ]]; then cat "$TMP"; found; else echo 'No direct cron references found.'; fi
  rm -f "$TMP"
elif command -v crontab >/dev/null 2>&1; then
  if crontab -l 2>/dev/null | grep -nF -- "$DIR"; then found; else echo 'No references in current user crontab; other users not checked.'; fi
  warn 'Other users crontabs require additional permissions.'
else
  echo 'INFO: crontab command not installed; user crontabs not inspectable by this method.'
  warn 'User crontabs were not checked.'
fi

section 'Summary'
printf 'Evidence groups with possible references: %d\n' "$MATCHES"
printf 'Active process evidence groups: %d\n' "$ACTIVE"
printf 'Configuration / indirect reference groups: %d\n' "$REFERENCES"
printf 'Scan warnings: %d\n' "$WARNINGS"
if (( ACTIVE > 0 )); then
  echo 'RESULT: IN_USE (direct process evidence observed; review details).'
elif (( REFERENCES > 0 )); then
  echo 'RESULT: REFERENCED (indirect/config references found; verify whether active).'
elif (( WARNINGS > 0 )); then
  echo 'RESULT: INCOMPLETE (no evidence found, but one or more checks failed or were skipped).'
else
  echo 'RESULT: NO_EVIDENCE (none found within the checked scope; NOT proof of unused).'
fi
if (( WARNINGS > 0 && MATCHES > 0 )); then
  echo 'WARNING: Some checks were incomplete; additional references may exist.'
fi
printf '%s\n' 'Not covered exhaustively: app-internal dynamic paths, every custom config, Kubernetes, remote CI/CD, historical use, and traffic metrics.'
